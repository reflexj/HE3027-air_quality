"""
HE3027 Group Project: data exploration of house prices and air pollution in London.

Creates:
    data_exploration.md               short write-up with the graphs and the regression
    figures/price_over_time.png       mean house price per quarter
    figures/pm10_over_time.png        mean PM10 per year

Run from the Code folder:
    python data_exploration.py

Needs: pandas, numpy, matplotlib
"""

from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

CODE_DIR = Path(__file__).resolve().parent
DATA_FILE = CODE_DIR / "data" / "land_registry_pollution.dta"
FIG_DIR = CODE_DIR / "figures"
MD_FILE = CODE_DIR / "data_exploration.md"

TRIM = 0.01          # drop the bottom and top 1% of prices
ACCENT = "#2a6ebb"


# ---------------------------------------------------------------------------
# Data
# ---------------------------------------------------------------------------
def load_data():
    cols = ["price", "pm10", "year", "yearquarter", "transactiondates"]
    df = pd.read_stata(DATA_FILE, columns=cols, convert_categoricals=False)
    n_raw = len(df)
    lo, hi = df["price"].quantile([TRIM, 1 - TRIM])
    df = df[df["price"].between(lo, hi)].copy()
    df["lnprice"] = np.log(df["price"])
    trim_info = {"n_raw": n_raw, "n_trimmed": len(df), "lo": lo, "hi": hi}
    return df, trim_info


# ---------------------------------------------------------------------------
# Graphs
# ---------------------------------------------------------------------------
def line_plot(series, ylabel, title, path):
    plt.rcParams.update({"axes.spines.top": False, "axes.spines.right": False,
                         "axes.grid": True, "grid.alpha": 0.3, "font.size": 10})
    fig, ax = plt.subplots(figsize=(9, 3.8))
    x = range(len(series))
    ax.plot(x, series.values, color=ACCENT, lw=2, marker="o", ms=4)
    labels = [str(i) for i in series.index]
    ticks = [i for i, q in enumerate(labels) if q.endswith("Q1") or "Q" not in q]
    ax.set_xticks(ticks)
    ax.set_xticklabels([labels[i][:4] for i in ticks])
    ax.set_xlabel("Year")
    ax.set_ylabel(ylabel)
    ax.set_title(title, loc="left")
    fig.tight_layout()
    fig.savefig(path, dpi=200)
    plt.close(fig)


# ---------------------------------------------------------------------------
# Simple regression: ln(price) = a + b * PM10 + e, robust (HC1) standard errors
# ---------------------------------------------------------------------------
def simple_ols(y, x):
    X = np.column_stack([np.ones(len(x)), x])
    XtX_inv = np.linalg.inv(X.T @ X)
    b = XtX_inv @ X.T @ y
    e = y - X @ b
    n, k = X.shape
    meat = (X * e[:, None]).T @ (X * e[:, None])
    V = XtX_inv @ meat @ XtX_inv * n / (n - k)
    se = np.sqrt(np.diag(V))
    r2 = 1 - (e @ e) / ((y - y.mean()) @ (y - y.mean()))
    return b, se, r2, n


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------
def main():
    FIG_DIR.mkdir(exist_ok=True)
    df, t = load_data()

    by_q = df.groupby("yearquarter").agg(price=("price", "mean")).sort_index()
    by_y = df.groupby("year").agg(pm10=("pm10", "mean")).sort_index()   # PM10 is a yearly average
    line_plot(by_q["price"] / 1000, "GBP 1,000", "Mean house price per quarter (prices trimmed at 1st/99th percentile)",
              FIG_DIR / "price_over_time.png")
    line_plot(by_y["pm10"], "µg/m³", "Mean PM10 per year",
              FIG_DIR / "pm10_over_time.png")

    b, se, r2, n = simple_ols(df["lnprice"].to_numpy(), df["pm10"].to_numpy())
    t_stat = b / se

    first, last = by_q.index[0], by_q.index[-1]
    p_first, p_last = by_q["price"].iloc[0], by_q["price"].iloc[-1]
    y_first, y_last = by_y.index[0], by_y.index[-1]
    q_first, q_last = by_y["pm10"].iloc[0], by_y["pm10"].iloc[-1]
    y_peak = by_y["pm10"].iloc[1:].idxmax()
    start = df["transactiondates"].min().date()
    end = df["transactiondates"].max().date()

    md = f"""# Overview: House Prices and Air Pollution in London

Generated by `data_exploration.py` from `data/land_registry_pollution.dta`.

## Data

- Land Registry house sales in London, {start} to {end}.
- **Prices are trimmed:** the bottom and top 1% of sale prices are dropped,
  i.e. sales below GBP {t['lo']:,.0f} and above GBP {t['hi']:,.0f}.
  This removes {t['n_raw'] - t['n_trimmed']:,} of {t['n_raw']:,} sales and leaves **{t['n_trimmed']:,} sales**.
- Air pollution is measured as PM10 (particulate matter, µg/m³) at the monitoring site nearest to each home, averaged over the year.
- 2015 only covers sales up to July.

## House prices over time

![Mean house price per quarter](figures/price_over_time.png)

The mean price rose from GBP {p_first:,.0f} in {first} to GBP {p_last:,.0f} in {last}.

## Air pollution over time

![Mean PM10 per year](figures/pm10_over_time.png)

PM10 is recorded as a yearly average, so it is shown per year (mean over all sales in that year).
Mean PM10 went from {q_first:.1f} µg/m³ in {y_first} to {q_last:.1f} µg/m³ in {y_last}.
The decline is not steady: after {y_first}, the highest value is in {y_peak} ({by_y['pm10'].loc[y_peak]:.1f} µg/m³).

## Simple regression

ln(price) = a + b · PM10 + e, estimated by OLS on the trimmed sample, robust standard errors.

| | Coefficient | Std. error | t-stat |
|---|---|---|---|
| Constant | {b[0]:.4f} | {se[0]:.4f} | {t_stat[0]:.1f} |
| PM10 | {b[1]:.5f} | {se[1]:.5f} | {t_stat[1]:.1f} |

Observations: {n:,}. R²: {r2:.4f}.

**Interpretation:** one extra µg/m³ of PM10 goes together with a {abs(b[1]) * 100:.2f}% {'higher' if b[1] > 0 else 'lower'} price.
This regression has no controls, so it is only a correlation: PM10 is higher near the centre,
where homes are more expensive for other reasons. It is not an estimate of the willingness to pay for clean air.
"""
    MD_FILE.write_text(md, encoding="utf-8")
    print(f"Wrote {MD_FILE} and the graphs in {FIG_DIR}")


if __name__ == "__main__":
    main()
